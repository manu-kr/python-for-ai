#Comparison operators
a = 10
b = 5
print(a > b)  # True
print(a < b)  # False
print(a >= b)  # True
print(a <= b)  # False
print(a == b)  # False
print(a != b)  # True   

#Logical operators
x = True
y = False
print(x and y)  # False
print(x or y)   # True
print(not x)    # False

#Assignment operators
x = 5
x += 3  # Equivalent to x = x + 3
print(x)  # 8

